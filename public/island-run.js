/* Island Run is a child view of the completed Arena result. It owns no tally scores. */
(function(root){
  'use strict';
  const classes=['5-A','5-C','6-C','7-A','8-B'],houses=['gryffindor','hufflepuff','slytherin','ravenclaw'];
  const $=id=>document.getElementById(id);
  let bridge=null,frame=null,context=null,signature='',token='',portraitBlob=null,loadTimer=null;
  let visible=false,ready=false,canPause=false,paused=false,lastStatus='map',focusBefore=null,navigator='',audio=false,voice='';
  const permitted=()=>Boolean(bridge?.eligible()&&root.LeagueAccess?.granted);
  // v9.3.0: listening starts on (opt-out), pictures start off (opt-in). Both are switchable from the remote.
  const OPTIONS_KEY='englishLeague.runOptions.v1';
  let options={listening:true,pictures:false};
  try{const saved=JSON.parse(localStorage.getItem(OPTIONS_KEY)||'null');if(saved&&typeof saved==='object')options={listening:saved.listening!==false,pictures:saved.pictures===true};}catch{}
  function setOptions(value){
    if(!value||typeof value!=='object')return {ok:false,message:'Unknown Island Run option'};
    const next={listening:typeof value.listening==='boolean'?value.listening:options.listening,pictures:typeof value.pictures==='boolean'?value.pictures:options.pictures};
    options=next;try{localStorage.setItem(OPTIONS_KEY,JSON.stringify(options));}catch{}
    try{frame?.contentWindow?.IslandRunner?.setOptions?.({...options});}catch{}
    changed();return {ok:true,message:`Listening ${options.listening?'on':'off'} · Pictures ${options.pictures?'on':'off'}`};
  }
  const snapshot=()=>({open:visible,ready,canPause:visible&&ready&&canPause,paused:visible&&paused,options:{...options},navigator:visible&&ready?navigator:'',audio:visible&&ready&&audio,voice:visible&&ready?voice:''});
  const changed=()=>bridge?.changed?.(snapshot());
  function refresh(){
    const winner=permitted()?bridge.context():null;
    const button=$('island-run-launch');if(!button)return;
    button.hidden=!winner||!houses.includes(winner.house);
    if(winner){button.setAttribute('aria-label',`Island Run with ${winner.name}, the Battle Arena champion`);button.style.setProperty('--island-team-color',({gryffindor:'#fb7185',hufflepuff:'#fbbf24',slytherin:'#34d399',ravenclaw:'#38bdf8'})[winner.house]||'#f6d48c');}
  }
  function assetFor(c){
    // Markup is generated by the tally's own avatar renderer, never from roster text.
    if(typeof c.avatarMarkup==='string'&&c.avatarMarkup.trim().startsWith('<svg')){
      const svg=c.avatarMarkup.replace('width="100%"','width="384"').replace('height="100%"','height="384"');
      portraitBlob=URL.createObjectURL(new Blob([svg],{type:'image/svg+xml'}));return portraitBlob;
    }
    return new URL(`assets/animated/${c.house}-${Math.max(0,Math.min(10,Math.round(c.level)||0))}.webp`,document.baseURI).href;
  }
  function disposeFrame(){
    clearTimeout(loadTimer);loadTimer=null;
    try{frame?.contentWindow?.IslandRunner?.setHostVisible(false);}catch{}
    frame?.remove();frame=null;context=null;signature='';token='';
    if(portraitBlob)URL.revokeObjectURL(portraitBlob);portraitBlob=null;
    ready=false;canPause=false;paused=false;lastStatus='map';navigator='';audio=false;voice='';
  }
  function hide(){
    if(!visible)return {ok:false,message:'Island Run is not open.'};
    // Keep an unfinished run paused in this same result; reopening can continue it.
    try{frame?.contentWindow?.IslandRunner?.setHostVisible(false);}catch{}
    visible=false;clearTimeout(loadTimer);loadTimer=null;root.LeagueRecap?.render();
    if(!ready)disposeFrame();
    $('island-run-overlay').hidden=true;$('island-run-overlay').setAttribute('aria-hidden','true');
    document.body.classList.remove('island-run-active');$('winner-overlay').inert=false;
    if(permitted())(focusBefore||$('island-run-launch')).focus({preventScroll:true});
    changed();return {ok:true};
  }
  function fail(){
    if(!visible||ready)return;
    $('island-run-loading').hidden=false;$('island-run-loading-text').textContent='Island Run could not finish loading. Try again, or return to the champions.';
    $('island-run-retry').hidden=false;
  }
  function launch(c){
    if(!permitted()||!classes.includes(c.className)||!houses.includes(c.house))return false;
    root.LeagueRecap?.begin(c.sessionId,c.className,LeagueIslandProgress.snapshot(c.className));
    const next=[c.sessionId,c.className,c.house,c.level,c.avatarMarkup,c.navigator?.id||''].join('|');
    $('island-run-class-picker').hidden=true;
    $('island-run-context').textContent=`${c.className} · ${c.name} · Level ${c.level}`;
    if(frame&&signature===next){
      frame.hidden=false;
      try{frame.contentWindow?.IslandRunner?.setHostVisible(true);}catch{}
      $('island-run-loading').hidden=ready;
      if(!ready)loadTimer=setTimeout(fail,15000);
      frame.focus();changed();return true;
    }
    disposeFrame();signature=next;token=LeagueRecovery.uid();
    // v9.7.0: one navigator for the whole session, chosen by the board from the champion team's contributors.
    const n=c.navigator,navigatorOk=n&&typeof n.id==='string'&&typeof n.name==='string'&&n.name.trim()&&houses.includes(n.team);
    const chosen=navigatorOk?Object.freeze({id:n.id.slice(0,100),name:n.name.trim().slice(0,70),team:n.team}):null;
    context=Object.freeze({version:3,token,sessionId:c.sessionId,className:c.className,grade:Number(c.className[0]),house:c.house,level:c.level,progress:LeagueIslandProgress.snapshot(c.className),avatar:assetFor(c),navigator:chosen,crew:Object.freeze(chosen?[chosen.name]:[])});
    $('island-run-loading').hidden=false;$('island-run-loading-text').textContent='Opening the islands…';$('island-run-retry').hidden=true;
    frame=document.createElement('iframe');frame.id='island-run-frame';frame.title=`Island Run · ${c.className} · ${c.name}`;
    frame.setAttribute('allow','fullscreen');frame.setAttribute('allowfullscreen','');
    frame.src='./island-runner/index.html?v=9.7.0';frame.addEventListener('error',fail);
    $('island-run-stage').append(frame);loadTimer=setTimeout(fail,15000);changed();return true;
  }
  function open(){
    if(!permitted())return {ok:false,message:'Finish the Battle Arena first.'};
    const c=bridge.context();if(!c||!houses.includes(c.house))return {ok:false,message:'No Battle Arena champion is available.'};
    focusBefore=document.activeElement;visible=true;
    $('island-run-overlay').hidden=false;$('island-run-overlay').setAttribute('aria-hidden','false');
    document.body.classList.add('island-run-active');$('winner-overlay').inert=true;$('island-run-back').focus();
    if(classes.includes(c.className))launch(c);
    else if(context?.sessionId===c.sessionId&&context.house===c.house)launch({...c,className:context.className});
    else{
      $('island-run-loading').hidden=true;$('island-run-class-picker').hidden=false;
      $('island-run-context').textContent=c.name;
      $('island-run-classes').replaceChildren(...classes.map(name=>{
        const button=document.createElement('button');button.type='button';button.textContent=name;
        button.onclick=()=>{if(visible&&permitted())launch({...c,className:name});};return button;
      }));changed();
    }
    return {ok:true};
  }
  function connect(child){
    if(!visible||!permitted()||child!==frame?.contentWindow||!context)return null;
    return {...context,progress:LeagueIslandProgress.snapshot(context.className),teaching:root.LeagueTeaching?.catalog(context.grade)};
  }
  function report(child,key,state){
    if(child!==frame?.contentWindow||key!==token||!permitted()||!state||typeof state!=='object')return false;
    const nextReady=state.ready===true,nextPause=state.canPause===true,nextPaused=state.paused===true;
    const status=['map','running','completed','ended'].includes(state.status)?state.status:'map';
    const nextNavigator=typeof state.navigator==='string'?state.navigator.slice(0,70):'',nextAudio=state.audio===true,nextVoice=typeof state.voice==='string'?state.voice.slice(0,90):'';
    const differs=ready!==nextReady||canPause!==nextPause||paused!==nextPaused||lastStatus!==status||navigator!==nextNavigator||audio!==nextAudio||voice!==nextVoice;
    ready=nextReady;canPause=nextPause;paused=nextPaused;lastStatus=status;navigator=nextNavigator;audio=nextAudio;voice=nextVoice;
    if(ready){clearTimeout(loadTimer);loadTimer=null;$('island-run-loading').hidden=true;}
    if(differs)changed();return true;
  }
  function togglePause(){
    if(!visible||!permitted()||!ready||!canPause)return {ok:false,message:'Choose an island on the board first.'};
    const api=frame?.contentWindow?.IslandRunner;if(!api)return {ok:false,message:'Island Run is loading.'};
    paused?api.resume():api.pause();return {ok:true};
  }
  function runnerCall(name,message){
    if(!visible||!permitted()||!ready)return {ok:false,message:'Open Island Run on the board first.'};
    const api=frame?.contentWindow?.IslandRunner;if(!api?.[name])return {ok:false,message:'Island Run is loading.'};
    return api[name]()||{ok:true,message};
  }
  const own=(child,key)=>child===frame?.contentWindow&&key===token&&Boolean(context)&&permitted();
  function dispose(){hide();disposeFrame();refresh();}
  function configure(adapter){
    bridge=adapter;$('island-run-launch').onclick=open;$('island-run-back').onclick=hide;
    $('island-run-retry').onclick=()=>{
      const c=bridge.context(),chosen=context?.className;disposeFrame();launch({...c,className:c.className||chosen});
    };
    refresh();
  }
  document.addEventListener('league-scene-change',()=>{if(bridge){if(!permitted())dispose();else refresh();}});
  root.addEventListener('storage',()=>{if(visible&&!root.LeagueAccess?.granted)hide();});
  root.addEventListener('pagehide',event=>{if(!event.persisted)disposeFrame();});
  root.LeagueIslandRun=Object.freeze({configure,open,close:hide,dispose,refresh,connect,report,togglePause,setOptions,
    get options(){return {...options};},
    repeatAudio:()=>runnerCall('repeatAudio','Repeating the word'),
    // v9.7.0: the navigator stays for the whole session; the remote's student controller steers the runner.
    nextNavigator:()=>({ok:false,message:'The navigator stays the same for the whole session.'}),
    control(action){
      if(!visible||!permitted()||!ready||!['up','down','jump'].includes(action))return false;
      try{return frame?.contentWindow?.IslandRunner?.control?.(action)===true;}catch{return false;}
    },
    sealFrom(child,key,island){
      if(!own(child,key)||!context.navigator)return null;
      const n=Number(island);if(!Number.isInteger(n)||n<1||n>10)return null;
      const result=root.LeagueNavigatorSeals?.award(context.className,context.navigator,n,context.sessionId);
      if(result?.added)bridge?.sealsChanged?.(context.className);
      return result?{added:result.added,count:result.count,name:result.name}:null;
    },
    answersFrom(child,key,rows){
      if(!own(child,key)||!Array.isArray(rows))return 0;
      const mine=rows.filter(r=>r&&r.c===context.className&&r.s===context.sessionId);
      const added=root.LeagueQuestionLog?.record(mine)||0;if(added)bridge?.questionsChanged?.(context.className);return added;
    },
    reviewFor(child,key,grade){return own(child,key)?root.LeagueQuestionLog?.review(context.className,grade)||[]:[];},
    clearReviewFrom(child,key){if(!own(child,key))return false;root.LeagueQuestionLog?.clearReview(context.className);return true;},
    optionsFor(child,key){return own(child,key)?{...options}:null;},
    optionsFrom(child,key,value){return own(child,key)?setOptions(value):null;},
    returnFrom(child,key){return child===frame?.contentWindow&&key===token?hide():{ok:false};},
    progressFrom(child,key,progress){if(child!==frame?.contentWindow||key!==token||!context||!permitted())return false;root.LeaguePassportSeals?.fromRun();return LeagueIslandProgress.merge(progress,context.className);},
    studioFrom(child,key,options){if(child!==frame?.contentWindow||key!==token||!context||!permitted())return false;return root.LeagueStudio?.open({className:context.className,island:options?.island})||false;},
    applyTeaching(value){try{frame?.contentWindow?.IslandRunner?.applyTeaching(value);}catch{}},
    applyProgress(progress){try{frame?.contentWindow?.IslandRunner?.applyProgress(progress);}catch{}},
    get state(){return snapshot();},get isOpen(){return visible;}});
})(window);
